// v0.716 NAYA ROOP: render the Hoola mark (server/app/static/console/mark.js, the ONE drawing) into the files that
// cannot be SVG. v0.887 ORBIT: the app icon is the mark in WHITE on an Espresso tile (#2A1C15), its needle running to the
// corners of the tile (mark.js draws in tile coordinates, 0..100 = the whole icon).
//   assets/images/hoola_logo.png         1024 master: the full Espresso square, needle tips just inside a 22% rounded corner
//                                        -> tool/make_logo.py builds every size from it
//   assets/images/hoola_logo_fg.png      1024 Android adaptive foreground: the white mark alone, drawn for a ROUND launcher
//                                        (needle stops inside the circle) and placed on the 72/108 visible area
//   server/app/static/hoola-mark.png      the LIGHT mark on transparent (console sidebar + sign-in, v0.720)
//   assets/images/mark_{outer,inner,needle,core}.png   the four layers the phone's thinking mark animates (white; the
//                                                      phone tints them with the theme's violet, lib/ui/hoola_mark.dart)
//   tool/android/res/drawable/ic_stat_santosh.xml      the status-bar silhouette (Android keeps only the shape)
// usage: node tool/make_mark.js   (from the repo root; uses the preinstalled Playwright Chromium)
'use strict';
const fs = require('fs');
const path = require('path');
const {chromium} = require('playwright');

const ROOT = path.resolve(__dirname, '..');
const MARK = fs.readFileSync(path.join(ROOT, 'server/app/static/console/mark.js'), 'utf8');

(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({viewport: {width: 1024, height: 1024}, deviceScaleFactor: 1});
  await p.setContent('<!doctype html><html><body style="margin:0;background:transparent"><div id="x" style="width:1024px;height:1024px"></div></body></html>');
  await p.addScriptTag({content: MARK});
  const shot = async (html, bg, file) => {
    await p.evaluate(([h, c]) => {
      const x = document.getElementById('x');
      x.style.background = c;
      x.innerHTML = h;
      const s = x.querySelector('svg'); if (s) { s.style.width = '100%'; s.style.height = '100%'; s.style.display = 'block'; }
    }, [html, bg]);
    await p.locator('#x').screenshot({path: path.join(ROOT, file), omitBackground: bg === 'transparent'});
    console.log(file);
  };
  const TILE = await p.evaluate(() => HoolaMark.tile);
  const white = await p.evaluate(() => HoolaMark.svg({color: '#FFFFFF', full: true}));
  const whiteRound = await p.evaluate(() => HoolaMark.svg({color: '#FFFFFF', full: true, shape: 'circle'}));
  const violet = await p.evaluate(() => HoolaMark.svg({color: HoolaMark.violet}));
  // the master: the whole tile - the white mark on Espresso, full bleed (launchers / iOS round the corners themselves)
  await shot(white, TILE, 'assets/images/hoola_logo.png');
  // the adaptive foreground: a launcher shows the inner 72 of the 108 dp layer, so the tile box maps onto that area
  // (padding 18 / 108 = 16.67%) and the needle is the ROUND one, stopping inside the circle mask
  await shot(`<div style="box-sizing:border-box;padding:16.667%;width:100%;height:100%">${whiteRound}</div>`, 'transparent', 'assets/images/hoola_logo_fg.png');
  // v0.720 the LIGHT mark: the violet mark on transparent, no tile, no ring - the console's sidebar / sign-in logo
  await p.setViewportSize({width: 256, height: 256});
  await p.evaluate(() => { const x = document.getElementById('x'); x.style.width = '256px'; x.style.height = '256px'; });
  await shot(`<div style="box-sizing:border-box;padding:2%;width:100%;height:100%">${violet}</div>`, 'transparent', 'server/app/static/hoola-mark.png');
  for (const [k, parts] of [['outer', 'o'], ['inner', 'i'], ['needle', 'n'], ['core', 'c']]) {
    const s = await p.evaluate(pp => HoolaMark.svg({parts: pp, color: '#FFFFFF'}), parts);
    await shot(s, 'transparent', `assets/images/mark_${k}.png`);
  }
  // the status-bar silhouette: same shapes, white, viewport 0..100 drawn in 24dp
  const P = await p.evaluate(() => HoolaMark.paths);
  const [bx, by, bw] = (await p.evaluate(() => HoolaMark.box)).split(' ').map(Number);
  const c = P.core;
  const circle = `M${c.cx - c.r},${c.cy}a${c.r},${c.r} 0 1,0 ${2 * c.r},0a${c.r},${c.r} 0 1,0 ${-2 * c.r},0Z`;
  const xml = `<!-- v0.716 the owner's new logo as the notification / quick-tile icon, generated by tool/make_mark.js from
     server/app/static/console/mark.js. Android strips every colour from a status-bar icon and keeps only the
     shape, so this is the mark as a flat white silhouette on transparent: the two outer ring halves, the two inner
     ring halves, the needle and the core (v0.887 Orbit). -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp" android:height="24dp" android:viewportWidth="${bw}" android:viewportHeight="${bw}">
  <group android:translateX="${-bx}" android:translateY="${-by}">
${['uo', 'lo', 'ui', 'li', 'needleMark'].map(k => `    <path android:fillColor="#FFFFFFFF" android:pathData="${P[k]}"/>`).join('\n')}
    <path android:fillColor="#FFFFFFFF" android:pathData="${circle}"/>
  </group>
</vector>
`;
  fs.writeFileSync(path.join(ROOT, 'tool/android/res/drawable/ic_stat_santosh.xml'), xml);
  console.log('tool/android/res/drawable/ic_stat_santosh.xml');
  await b.close();
})();

def install() -> None:
    """Put the 72 desks into the Hub's catalogue (once; an entry already there is never overwritten)."""
    for key, (name, group, pitch, does, tail) in TEAM.items():
        if key in H.CATALOG:
            continue
        H.CATALOG[key] = {"name": name, "live": True, "icon": "work", "group": group, "pitch": pitch,
                          "does": does + ([tail[0].upper() + tail[1:]] if tail else []), "needs": [],
                          "never": NEVER, "desk": DESK.get(key, "deptdesk"), "team_desk": True}


install()

from __future__ import annotations

from typing import Any


def _s(label: str, hi: str, why: str, data: str, *variants: str) -> dict[str, Any]:
    assert len(variants) == 6, label
    return {"label": label, "hi": hi, "why": why, "data": [d for d in data.split(",") if d], "variants": list(variants), "pro": True}



"""v0.999.51 D1 THE KIT (docs/WEB_DESIGN_ENGINE_PLAN.md P1 + phase D1): the one React kit websites and apps share.

What is in the template (`template/src/components/`):
- `ui/` - the full shadcn/ui-style set (~45 parts) on Radix / vaul / cmdk / react-day-picker / embla / recharts,
  restyled onto the app's design tokens only (tokens.css), changed through cva variants.
- `effects/` - a few CSS-only moments (reveal, number ticker, marquee, patterns, spotlight card, word rotate, border
  beam); ideas from Magic UI and React Bits (MIT, the owner's 20 Nov decision), written for Hoola - no upstream code.
- `blocks/` - the 39 section types of site/taxonomy.py as React blocks (30 website sections + 9 app screens). Every
  block is a <section data-block="<id>">, has 2-3 layout variants and believable sample content as its defaults, and
  reads ONLY the tokens - so any design system ("genome", phase D2) restyles every block at once.

The D1 done-line: every block renders in 3 genomes with 0 rule breaks. `render_check()` proves it for real: the kit
gallery (every block in every variant) is built in the App Engine box once per genome, opened in Chromium on a
computer and a phone width, and every block must be there, non-empty, with no page error and no sideways scroll;
`rule_check()` runs rules.py (safety, drift, taste) over every kit file; each genome passes the contrast floor.
`python -m app.appengine kit [--no-browser] [--shots DIR]`."""
from __future__ import annotations

import json
import os
import shutil
import tempfile
import time
from pathlib import Path
from typing import Any

from . import image as IMG
from . import rules as RL
from . import tokens as TK

TEMPLATE = Path(__file__).resolve().parent / "template"
UI = TEMPLATE / "src" / "components" / "ui"
EFFECTS = TEMPLATE / "src" / "components" / "effects"
BLOCKS_DIR = TEMPLATE / "src" / "components" / "blocks"
WIDTHS = (1280, 390)
# three genomes that pull the kit apart: neutral sans light / warm serif with sharp corners / dark
GENOMES: dict[str, dict[str, Any]] = {
    "calm": {"palette": "calm", "values": {}},
    "warm-sharp": {"palette": "warm", "values": {"radius": 2}},
    "night": {"palette": "night", "values": {"radius": 20}},
}


def block_ids() -> list[str]:
    from ..site import taxonomy as TX
    return list(TX.SECTIONS)


def file_of(block: str) -> str:
    return block.replace("_", "-") + ".tsx"


def comp_of(block: str) -> str:
    return "".join(p.capitalize() for p in block.split("_"))


def missing_blocks() -> list[str]:
    return [b for b in block_ids() if not (BLOCKS_DIR / file_of(b)).exists()]


def ui_parts() -> list[str]:
    return sorted(p.stem for p in UI.glob("*.tsx"))


def kit_files() -> list[Path]:
    return sorted(p for d in (UI, EFFECTS, BLOCKS_DIR) for p in d.rglob("*") if p.suffix in (".ts", ".tsx"))


def rule_check() -> list[dict[str, Any]]:
    """rules.py on every kit file, with the packages every new app carries (the template's own)."""
    deps = set(IMG.CORE) | set(IMG.DEV)
    out: list[dict[str, Any]] = []
    for p in kit_files():
        rel = p.relative_to(TEMPLATE).as_posix()
        out += RL.check_file(rel, p.read_text("utf-8"), deps)
    return out


def genome_tokens(name: str) -> dict[str, Any]:
    g = GENOMES[name]
    return TK.resolve(g["values"], g["palette"])


def gallery_page() -> str:
    """src/pages/Kit.tsx of the gallery app: every block in every variant, each wrapped with its id + variant."""
    ids = block_ids()
    imp = "\n".join(f'import * as {comp_of(b)} from "@/components/blocks/{file_of(b)[:-4]}";' for b in ids)
    rows = ",\n".join(f'  ["{b}", {comp_of(b)}]' for b in ids)
    return f"""// generated by app/appengine/kit.py - the kit gallery (every block, every variant). Not part of any app.
import * as React from "react";
{imp}

type Mod = {{ default: React.ComponentType<{{ variant?: any }}>; variants: readonly string[] }};
const ALL: [string, Mod][] = [
{rows}
];

export default function Kit() {{
  return (
    <main>
      {{ALL.map(([id, M]) =>
        M.variants.map((v) => (
          // a floating block (fixed on the page) is held inside its own box here, so it never covers the others
          <div key={{id + v}} data-kit-item={{id}} data-kit-variant={{v}}
            style={{id === "whatsapp_float" ? {{ position: "relative", height: 180, overflow: "hidden", transform: "translateZ(0)" }} : undefined}}>
            <M.default variant={{v}} />
          </div>
        )),
      )}}
    </main>
  );
}}
"""


GALLERY_APP = """import { Routes, Route } from "react-router-dom";
import Kit from "./pages/Kit";

export default function App() {
  return (
    <Routes>
      <Route path="*" element={<Kit />} />
    </Routes>
  );
}
"""


def gallery_dir(genome: str, dest: Path) -> Path:
    shutil.copytree(TEMPLATE, dest, dirs_exist_ok=True)
    (dest / "src" / "styles").mkdir(parents=True, exist_ok=True)
    (dest / "src" / "styles" / "tokens.css").write_text(TK.css(genome_tokens(genome)), "utf-8")
    (dest / "package.json").write_text(json.dumps(IMG.project_package("hoola-kit"), indent=2) + "\n", "utf-8")
    (dest / "src" / "App.tsx").write_text(GALLERY_APP, "utf-8")
    (dest / "src" / "pages" / "Kit.tsx").write_text(gallery_page(), "utf-8")
    return dest


_WALK = """() => {
  const items = [...document.querySelectorAll('[data-kit-item]')];
  const out = items.map((w) => {
    const sec = w.querySelector('[data-block]');
    const r = (sec || w).getBoundingClientRect();
    return { id: w.dataset.kitItem, variant: w.dataset.kitVariant, block: sec ? sec.dataset.block : '',
             h: Math.round(r.height), text: ((sec || w).textContent || '').trim().length,
             // content clipped on purpose (overflow hidden / clip: a decorative shape) is not overflow
             wide: sec && !['hidden', 'clip'].includes(getComputedStyle(sec).overflowX)
               ? Math.max(0, Math.round(sec.scrollWidth - sec.clientWidth)) : 0 };
  });
  return { items: out, sideways: Math.max(0, document.documentElement.scrollWidth - window.innerWidth) };
}"""


def _browse(url: str, widths=WIDTHS, shots: str = "", tag: str = "") -> dict[str, Any]:
    from playwright.sync_api import sync_playwright
    exe = os.environ.get("HOOLA_CHROMIUM") or None
    res: dict[str, Any] = {}
    with sync_playwright() as pw:
        b = pw.chromium.launch(**({"executable_path": exe} if exe else {}))
        try:
            for w in widths:
                pg = b.new_page(viewport={"width": w, "height": 900})
                errs: list[str] = []
                pg.on("pageerror", lambda e: errs.append(str(e)[:300]))
                pg.on("console", lambda m: errs.append(m.text[:300]) if m.type == "error" else None)
                pg.goto(url, wait_until="networkidle")
                pg.wait_for_selector("[data-kit-item]", timeout=20000)
                pg.wait_for_timeout(400)
                d = pg.evaluate(_WALK)
                d["errors"] = errs
                if shots:                       # one picture per block + variant (the whole gallery is too tall for a jpeg)
                    Path(shots).mkdir(parents=True, exist_ok=True)
                    items = pg.locator("[data-kit-item]")
                    for i in range(items.count()):
                        it = items.nth(i)
                        it.scroll_into_view_if_needed()
                        pg.wait_for_timeout(60)
                        name = f"{tag}-{w}-{it.get_attribute('data-kit-item')}-{it.get_attribute('data-kit-variant')}.jpg"
                        try:
                            it.screenshot(path=str(Path(shots) / name), type="jpeg", quality=60, timeout=8000)
                        except Exception:                # noqa: BLE001 - a picture is a convenience, never a verdict
                            pass
                res[str(w)] = d
                pg.close()
        finally:
            b.close()
    return res


def _static(root: Path):
    """A tiny local server for the built gallery (modules do not load from file://)."""
    import functools
    import http.server
    import socketserver
    import threading

    class H(http.server.SimpleHTTPRequestHandler):
        def log_message(self, *a):
            pass

    srv = socketserver.ThreadingTCPServer(("127.0.0.1", 0), functools.partial(H, directory=str(root)))
    srv.daemon_threads = True
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    return srv, srv.server_address[1]


def judge(view: dict[str, Any], width: int) -> list[str]:
    """What a block got wrong on one page width (empty = every block rendered)."""
    probs: list[str] = []
    want = {b for b in block_ids()}
    seen = {x["id"] for x in view["items"]}
    probs += [f"{b}: not in the gallery" for b in sorted(want - seen)]
    for x in view["items"]:
        name = f"{x['id']}/{x['variant']}"
        if x["block"] != x["id"]:
            probs.append(f"{name}: root is not <section data-block=\"{x['id']}\">")
        float_only = x["id"] == "whatsapp_float"
        if not float_only and x["h"] < 40:                       # a thin offer strip is ~50 px on purpose
            probs.append(f"{name}: only {x['h']}px tall")
        if x["text"] < 6:
            probs.append(f"{name}: shows no words")
        if x["wide"] > 1:
            probs.append(f"{name}: {x['wide']}px wider than the page at {width}px")
    if view.get("sideways", 0) > 1:
        probs.append(f"page scrolls sideways by {view['sideways']}px at {width}px")
    probs += [f"page error at {width}px: {e}" for e in view.get("errors", [])[:10]]
    return probs


def render_check(browser: bool = True, shots: str = "", genomes: tuple[str, ...] = tuple(GENOMES)) -> dict[str, Any]:
    """The D1 done-line, for real. Never raises; `verdict` PASS / FAIL with every problem named."""
    from . import runner as RN
    t0 = time.time()
    rows: list[dict[str, Any]] = []
    rules = rule_check()
    miss = missing_blocks()
    av = RN.available()
    for g in genomes:
        row: dict[str, Any] = {"genome": g, "contrast": TK.audit(genome_tokens(g)), "problems": []}
        row["problems"] += [f"contrast: {c}" for c in row["contrast"]]
        if not av["ok"]:
            row["problems"].append("not built: " + av["why"])
            rows.append(row)
            continue
        with tempfile.TemporaryDirectory(prefix="hoola-kit-") as tmp:
            src = gallery_dir(g, Path(tmp) / "app")
            b = RN.build(src, wait=120.0, source=False)
            row["build_s"] = b.get("seconds")
            if not b.get("ok"):
                row["problems"] += ["build: " + (x.get("file", "") + ":" + str(x.get("line", "")) + " " + x["message"])
                                    for x in (b.get("build_problems") or [])[:8]] or ["build: " + str(b.get("why"))]
            if not b.get("types_ok", False):
                row["problems"] += [f"types: {x['file']}:{x['line']} {x['message']}" for x in (b.get("types") or [])[:12]]
            if b.get("ok") and browser:
                site = Path(tmp) / "site"
                shutil.copytree(b["dist"], site)
                srv, port = _static(site)
                try:
                    view = _browse(f"http://127.0.0.1:{port}/index.html", shots=shots, tag=g)
                except Exception as e:                                   # noqa: BLE001 - said, never raised
                    view = {}
                    row["problems"].append(f"browser: {str(e)[:300]}")
                finally:
                    srv.shutdown()
                row["widths"] = {}
                for w, v in view.items():
                    ps = judge(v, int(w))
                    row["widths"][w] = {"items": len(v["items"]), "problems": len(ps)}
                    row["problems"] += ps
            shutil.rmtree(b.get("out_dir") or "/nonexistent", ignore_errors=True)
        rows.append(row)
    bad = bool(rules) or bool(miss) or any(r["problems"] for r in rows)
    return {"verdict": "FAIL" if bad else "PASS", "blocks": len(block_ids()) - len(miss), "missing": miss,
            "ui_parts": len(ui_parts()), "rule_problems": rules[:40], "rules": len(rules), "genomes": rows,
            "browser": browser, "seconds": round(time.time() - t0, 1)}


def prompt_line() -> str:
    """One line for the model: what the kit holds (the writer of D4 uses the blocks; App Engine apps may already)."""
    return ("The kit: src/components/ui (" + ", ".join(ui_parts()) + "), src/components/effects (Reveal, NumberTicker, "
            "Marquee, DotPattern, GridPattern, SpotlightCard, WordRotate, BorderBeam) and src/components/blocks - one "
            "React block per section type (" + ", ".join(file_of(b)[:-4] for b in block_ids()) + "), each with "
            "`variants` and sample defaults: build pages from these, never from scratch.")

"""v0.802 DEVICE (Android kit): biometric lock, rate the app, add to calendar, pick a contact, accessibility labels.
Pure string / generator checks - the kit itself compiles only on GitHub CI (appgen-check, fixture dashboard)."""
from __future__ import annotations

import json
import re
from pathlib import Path

from app.appmaker.android import gen as AG
from app.appmaker.android import prompts as AP

KIT = AG.TEMPLATE / "app/src/main/java/hoola/kit"
FIX = Path(AG.__file__).resolve().parent / "fixture"
NAMES = ("BiometricLock", "RateAppButton", "AddToCalendarButton", "PickContactButton")


def test_device_kt_has_the_public_names():
    src = (KIT / "Device.kt").read_text()
    assert src.startswith("package hoola.kit")
    assert re.search(r"@Composable\s+fun BiometricLock\(reason: String, onOk: \(\) -> Unit\)", src)
    assert re.search(r"@Composable\s+fun RateAppButton\(\)", src)
    assert re.search(r"@Composable\s+fun AddToCalendarButton\(title: String, startMillis: Long, endMillis: Long, location: String = \"\", notes: String = \"\"\)", src)
    assert re.search(r"@Composable\s+fun PickContactButton\(onPicked: \(name: String, phone: String\) -> Unit\)", src)
    for helper in ("fun askBiometric(", "fun askForReview(", "fun addToCalendar("):
        assert helper in src
    # framework BiometricPrompt (MainActivity is a ComponentActivity: androidx.biometric would need a FragmentActivity)
    assert "android.hardware.biometrics.BiometricPrompt" in src and "androidx.biometric" not in src
    assert "class MainActivity : ComponentActivity()" in Path(AG.__file__).read_text()
    # no READ_CONTACTS: the Phone picker grants a one-time read of the picked row
    assert "ContactsContract.CommonDataKinds.Phone.CONTENT_URI" in src and "permission.READ_CONTACTS" not in src
    assert "CalendarContract.Events.CONTENT_URI" in src and "Intent.ACTION_INSERT" in src
    assert "market://details?id=" in src and "https://play.google.com/store/apps/details?id=" in src


def test_strings_used_by_device_exist():
    src = (KIT / "Device.kt").read_text()
    strings = (KIT / "Strings.kt").read_text()
    for name in sorted(set(re.findall(r"Strings\.(\w+)", src))):
        assert re.search(rf"\bval {name} get\(\)", strings), name


def test_prompt_tells_the_model():
    sheet = AP.kit_sheet()
    for n in NAMES:
        assert n in sheet and n in AP.SCREEN_SYSTEM
    assert "Device.askForReview" in sheet and "Device.addToCalendar" in sheet
    assert "pickedContact" not in sheet and "onAuthentication" not in sheet


def test_biometric_permission_only_when_used():
    plain = AG.manifest_xml({})
    assert "USE_BIOMETRIC" not in plain
    other = {"screens_kt": {"home": "package hoola.app.screens\n@Composable fun ScreenHome() { RateAppButton() }"}}
    assert "USE_BIOMETRIC" not in AG.manifest_xml(other)
    used = {"screens_kt": {"home": 'package hoola.app.screens\n@Composable fun ScreenHome() { BiometricLock("x") { } }'}}
    assert '<uses-permission android:name="android.permission.USE_BIOMETRIC" />' in AG.manifest_xml(used)
    custom = {"custom": [{"name": "Vault", "kotlin": "fun Vault() { Device.askBiometric(c, \"r\", {}) }"}]}
    assert AG.uses_biometric(custom)
    # no other new permission rides along (calendar / contacts / Play page need none)
    for perm in ("READ_CONTACTS", "WRITE_CALENDAR", "READ_CALENDAR"):
        assert perm not in AG.manifest_xml(used)


def test_no_new_library():
    toml = (AG.TEMPLATE / "gradle/libs.versions.toml").read_text()
    gradle = (AG.TEMPLATE / "app/build.gradle.kts").read_text()
    assert "biometric" not in toml and "play-review" not in toml and "biometric" not in gradle


def test_fixture_compiles_every_feature():
    dash = (FIX / "screens/ScreenDashboard.kt").read_text()
    for n in NAMES:
        assert n + "(" in dash or n + " {" in dash, n
    spec = json.loads((FIX / "spec.json").read_text())
    src = spec["screens_kt"]["dashboard"]
    assert src == dash                       # spec.json regenerated by fixture_make
    ids = [s["id"] for s in spec["screens"]]
    assert AG.scan_screen(src, "dashboard", ids) == []
    assert "USE_BIOMETRIC" in AG.manifest_xml(spec)


